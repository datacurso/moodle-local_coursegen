namespace local_coursegen\mod_settings;

use stdClass;

/**
 * Class data_settings
 *
 * Creates the database fields (columns) generated by the AI service after the database instance
 * exists. The standard module creation cannot create fields, so without this a database activity
 * has no columns and is unusable. Each definition is written through mod_data's native field API
 * (data_get_field_new -> define_field -> insert_field). A template column is written only when the
 * payload carries it: an absent one is generated lazily by mod_data the first time it is rendered
 * (manager::get_template falls back to data_generate_default_template when a stored template is
 * empty), exactly as for a database a teacher builds by hand. When no fields are present the class
 * does nothing.
 *
 * Two payload shapes reach this class. A model-designed database states its fields loosely (type,
 * name, options) and the per-type heuristics below fill the rest in. A mold exported by
 * template_activity_export states them exactly - every param, every template column and the name
 * of the field it sorts by - and those explicit values always win, so the generated database is
 * the mold rather than an approximation of it.
 *
 * @package    local_coursegen
 * @copyright  2026 Wilber Narvaez <https://datacurso.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class data_settings extends base_settings {
    /** @var string[] Field types that store their choices, one per line, in param1. */
    private const CHOICE_TYPES = ['menu', 'multimenu', 'radiobutton', 'checkbox'];

    /** @var string[] Field types that make a sensible default sort key (identifying columns). */
    private const SORTABLE_TYPES = ['text', 'number', 'date', 'url', 'menu', 'radiobutton'];

    /**
     * The param columns data_field_base::define_field() actually reads (mod/data/lib.php).
     *
     * @var string[]
     */
    private const DEFINED_PARAMS = ['param1', 'param2', 'param3', 'param4', 'param5'];

    /**
     * The param columns a data_fields row owns beyond those define_field() reads.
     *
     * They exist in the table but never reach the field API, so a mold that uses them
     * needs them written straight onto the row after insert_field().
     *
     * @var string[]
     */
    private const EXTRA_PARAMS = ['param6', 'param7', 'param8', 'param9', 'param10'];

    /** @var string[] Every template column mod_data owns (see its install.xml). */
    private const TEMPLATE_COLUMNS = [
        'singletemplate', 'listtemplate', 'listtemplateheader', 'listtemplatefooter',
        'addtemplate', 'rsstemplate', 'rsstitletemplate', 'csstemplate', 'jstemplate',
        'asearchtemplate',
    ];

    /**
     * Per-type param defaults applied when creating a field programmatically.
     *
     * Creating a field by code skips the edit form, so type params start empty. For most types
     * that is fine, but a few render poorly without them, so we replicate mod_data's own form
     * defaults: textarea would otherwise be a tiny box with no editor, picture would show
     * full-resolution images in lists, and a url would not be a clickable link.
     *
     * @var array<string, array<string, string>>
     */
    private const TYPE_DEFAULTS = [
        // The param2 = columns, param3 = rows, param4 = use HTML editor, param5 = max size (0 = none).
        'textarea' => ['param2' => '60', 'param3' => '35', 'param4' => '1', 'param5' => '0'],
        // The param1/param2 = list thumbnail width/height, param4/param5 = single-view width/height.
        'picture'  => ['param1' => '100', 'param2' => '200', 'param4' => '300', 'param5' => '400'],
        // The param1 = autolink (make the URL a clickable link).
        'url'      => ['param1' => '1'],
    ];

    /**
     * Create the database fields, when any were generated.
     */
    public function add_settings() {
        global $CFG, $DB;

        $fields = $this->modsettings['fields'] ?? [];
        if (empty($fields) || !is_array($fields)) {
            return;
        }

        $dataid = (int) ($this->cm->instance ?? 0);
        if (!$dataid) {
            return;
        }

        require_once($CFG->dirroot . '/mod/data/lib.php');

        $datainstance = $DB->get_record('data', ['id' => $dataid]);
        if (!$datainstance) {
            return;
        }

        $created = [];
        foreach ($fields as $fieldspec) {
            if (is_array($fieldspec)) {
                $field = $this->create_field($datainstance, $fieldspec);
                if ($field !== null) {
                    $created[] = $field;
                }
            }
        }

        $this->set_default_sort($datainstance, $created);
        $this->set_templates($datainstance);
        $this->seed_example_entries($datainstance, $created);
    }

    /**
     * Seed the AI-generated example entries (already validated service-side) as approved records.
     *
     * Each value is serialised into data_content per field type (direct insert — mod_data's
     * update_content is form-shaped for some types). An entry that errors is skipped (a bad
     * example must never break the activity). Unseedable types and unknown fields are ignored.
     *
     * @param stdClass $datainstance The database activity record.
     * @param array $created Created fields as objects with ->id, ->type, ->name.
     */
    protected function seed_example_entries(stdClass $datainstance, array $created): void {
        global $USER;

        $entries = $this->modsettings['example_entries'] ?? [];
        if (empty($entries) || !is_array($entries)) {
            return;
        }

        $byname = [];
        foreach ($created as $field) {
            $byname[\core_text::strtolower($field->name)] = $field;
        }

        foreach ($entries as $entry) {
            $values = is_array($entry) ? ($entry['values'] ?? []) : [];
            if (empty($values) || !is_array($values)) {
                continue;
            }
            try {
                $recordid = data_add_record($datainstance, 0, $USER->id, true);
                foreach ($values as $pair) {
                    if (!is_array($pair)) {
                        continue;
                    }
                    $field = $byname[\core_text::strtolower(trim((string) ($pair['field_name'] ?? '')))] ?? null;
                    if ($field !== null) {
                        // A row states value1 only for a type that really owns a second
                        // stored column (a url's visible link text). Its absence is what
                        // keeps every payload written before it existed behaving as it did.
                        $this->insert_content(
                            $recordid,
                            $field,
                            (string) ($pair['value'] ?? ''),
                            array_key_exists('value1', $pair) ? (string) $pair['value1'] : null
                        );
                    }
                }
            } catch (\Throwable $e) {
                debugging('local_coursegen: skipped example entry: ' . $e->getMessage(), DEBUG_DEVELOPER);
            }
        }
    }

    /**
     * Serialise one field value into a data_content row according to the field type.
     *
     * @param int $recordid The entry record id.
     * @param stdClass $field The created field (->id, ->type).
     * @param string $rawvalue The validated value as text.
     * @param string|null $rawvalue1 The second stored value, when the type owns one
     *     (a url's visible link text); null when the payload states none.
     */
    protected function insert_content(
        int $recordid,
        stdClass $field,
        string $rawvalue,
        ?string $rawvalue1 = null
    ): void {
        global $DB;

        $value = trim($rawvalue);
        if ($value === '' || in_array($field->type, ['file', 'picture'], true)) {
            return;
        }

        $content = (object) ['fieldid' => $field->id, 'recordid' => $recordid, 'content' => $value];
        switch ($field->type) {
            case 'number':
                // Moodle stores numbers via floatval; keep non-numeric text out of the column
                // (it would display raw and break sorting on that field).
                if (!is_numeric($value)) {
                    return;
                }
                $content->content = (string) (float) $value;
                break;
            case 'date':
                $timestamp = strtotime($value);
                if ($timestamp === false) {
                    return;
                }
                $content->content = (string) $timestamp;
                break;
            case 'menu':
            case 'radiobutton':
                // Mod_data renders a stored choice only when it exactly matches a defined option,
                // so a mismatched value would show as blank: skip it instead of storing it.
                if (!in_array($value, $field->options ?? [], true)) {
                    return;
                }
                break;
            case 'multimenu':
            case 'checkbox':
                $parts = array_filter(array_map('trim', explode(',', $value)), static fn($p) => $p !== '');
                // Same exact-match rule as menu: mod_data silently drops non-matching tokens at
                // render time, so only tokens that are defined options are worth storing.
                $parts = array_values(array_intersect($parts, $field->options ?? []));
                if (empty($parts)) {
                    return;
                }
                $content->content = implode('##', $parts);
                break;
            case 'latlong':
                $parts = array_map('trim', explode(',', $value));
                if (count($parts) < 2 || !is_numeric($parts[0]) || !is_numeric($parts[1])) {
                    return;
                }
                $content->content = $parts[0];
                $content->content1 = $parts[1];
                break;
            case 'url':
                // Exactly what data_field_url::update_content() does to a typed-in
                // link: PARAM_URL on the address, PARAM_NOTAGS on the visible text,
                // and http:// prepended to an address that names no scheme and is
                // not a relative path. Storing the address verbatim (what the
                // default branch did) left mod_data rendering dead links.
                $address = clean_param($value, PARAM_URL);
                if ($address === '') {
                    return;
                }
                if (strpos($address, '://') === false && strpos($address, '/') !== 0) {
                    $address = 'http://' . $address;
                }
                $content->content = $address;
                if ($rawvalue1 !== null) {
                    $content->content1 = clean_param($rawvalue1, PARAM_NOTAGS);
                }
                break;
            case 'textarea':
                $content->content1 = FORMAT_HTML;
                break;
        }
        $DB->insert_record('data_content', $content);
    }

    /**
     * Apply the AI-designed display templates (already validated service-side) to the database.
     *
     * Every template column mod_data owns is accepted, and only the non-empty ones are written;
     * an absent or empty template leaves the column untouched so Moodle auto-generates its
     * default. A mold ships the columns it actually authored, so the generated database reads
     * like the mold instead of like a generic list.
     *
     * @param stdClass $datainstance The database activity record.
     */
    protected function set_templates(stdClass $datainstance): void {
        global $DB;

        $templates = $this->modsettings['templates'] ?? null;
        if (empty($templates) || !is_array($templates)) {
            return;
        }

        $update = ['id' => $datainstance->id];
        foreach (self::TEMPLATE_COLUMNS as $name) {
            $value = trim((string) ($templates[$name] ?? ''));
            if ($value !== '') {
                $update[$name] = $value;
            }
        }
        if (count($update) > 1) {
            $DB->update_record('data', (object) $update);
        }
    }

    /**
     * Sort the database by its primary identifying field instead of by time added.
     *
     * A mold names the field it sorts by (data.defaultsort is a row id of the mold, meaningless
     * here), so that name wins when one of the created fields carries it, together with the
     * mold's own direction. Otherwise the first created field of a sortable type
     * (text/number/date/url/menu/radiobutton) is used; if every field is a non-sortable type
     * (textarea/file/picture/latlong/multimenu/checkbox) the default time-added sort is kept
     * (defaultsort stays 0). Runs after the fields exist so the chosen defaultsort always
     * points at a real field id.
     *
     * @param stdClass $datainstance The database activity record.
     * @param array $created Created fields as objects with ->id, ->type and ->name, in creation order.
     */
    protected function set_default_sort(stdClass $datainstance, array $created): void {
        global $DB;

        $named = trim((string) ($this->modsettings['defaultsortfield'] ?? ''));
        if ($named !== '') {
            foreach ($created as $field) {
                if (\core_text::strtolower($field->name) === \core_text::strtolower($named)) {
                    $DB->update_record('data', (object) [
                        'id' => $datainstance->id,
                        'defaultsort' => $field->id,
                        'defaultsortdir' => (int) ($this->modsettings['defaultsortdir'] ?? 0),
                    ]);
                    return;
                }
            }
        }

        foreach ($created as $field) {
            if (in_array($field->type, self::SORTABLE_TYPES, true)) {
                $DB->update_record('data', (object) [
                    'id' => $datainstance->id,
                    'defaultsort' => $field->id,
                    'defaultsortdir' => 0,
                ]);
                return;
            }
        }
    }

    /**
     * Create a single field from its AI definition.
     *
     * Invalid definitions are skipped rather than failing the whole activity: an empty name or
     * type, a duplicate name (the module requires unique field names), an unknown field type, or
     * a choice field with no options.
     *
     * @param stdClass $datainstance The database activity record.
     * @param array $spec The field definition (type, name, description, required, options).
     * @return stdClass|null The created field (->id, ->type), or null when skipped/failed.
     */
    protected function create_field(stdClass $datainstance, array $spec): ?stdClass {
        $type = trim((string) ($spec['type'] ?? ''));
        $name = trim((string) ($spec['name'] ?? ''));
        if ($type === '' || $name === '') {
            return null;
        }
        if (data_fieldname_exists($name, $datainstance->id)) {
            return null;
        }

        $formdata = $this->build_formdata($type, $name, $spec);
        // A choice field with no usable options cannot be filled in -> skip it.
        if (in_array($type, self::CHOICE_TYPES, true) && trim((string) ($formdata->param1 ?? '')) === '') {
            return null;
        }

        // A single problematic field (unknown/disabled type, a DB error, an over-long name, ...)
        // must never abort the activity creation or the remaining fields: this runs after the
        // module already exists, so a thrown error would leave a half-built database.
        try {
            $field = data_get_field_new($type, $datainstance);
            $field->define_field($formdata);
            $field->insert_field();
            $this->write_extra_params((int) $field->field->id, $spec);
            $options = in_array($type, self::CHOICE_TYPES, true)
                ? explode("\n", (string) $formdata->param1)
                : [];
            return (object) [
                'id' => (int) $field->field->id,
                'type' => $type,
                'name' => $name,
                'options' => $options,
            ];
        } catch (\Throwable $e) {
            debugging(
                'local_coursegen: skipped data field "' . $name . '": ' . $e->getMessage(),
                DEBUG_DEVELOPER
            );
            return null;
        }
    }

    /**
     * Build the form-data object define_field() expects from the AI field definition.
     *
     * @param string $type The Moodle field type.
     * @param string $name The (validated) field name.
     * @param array $spec The field definition.
     * @return stdClass
     */
    protected function build_formdata(string $type, string $name, array $spec): stdClass {
        $formdata = new stdClass();
        $formdata->name = $name;
        $formdata->description = trim((string) ($spec['description'] ?? ''));
        $formdata->required = !empty($spec['required']) ? 1 : 0;

        // A mold ships the field's real definition in param1..param10; it replaces the
        // options/TYPE_DEFAULTS guesses entirely, so the created column IS the mold's column.
        $explicit = $this->explicit_params($spec);
        if ($explicit) {
            foreach (self::DEFINED_PARAMS as $param) {
                if (array_key_exists($param, $explicit)) {
                    $formdata->$param = $explicit[$param];
                }
            }
            return $formdata;
        }

        foreach (self::TYPE_DEFAULTS[$type] ?? [] as $param => $value) {
            $formdata->$param = $value;
        }

        if (in_array($type, self::CHOICE_TYPES, true)) {
            // Types menu/multimenu/radiobutton/checkbox read their options from param1, one per line.
            $formdata->param1 = implode("\n", $this->clean_options($spec['options'] ?? []));
        }

        return $formdata;
    }

    /**
     * The field params a definition states explicitly, as strings.
     *
     * A null param means "this type does not use it" and is left out, so the column keeps the
     * NULL the mold has; an empty string is a real value and travels as such.
     *
     * @param array $spec The field definition.
     * @return array<string, string> Param name => value, empty when the definition states none.
     */
    protected function explicit_params(array $spec): array {
        $params = [];
        foreach (array_merge(self::DEFINED_PARAMS, self::EXTRA_PARAMS) as $param) {
            if (array_key_exists($param, $spec) && $spec[$param] !== null) {
                $params[$param] = (string) $spec[$param];
            }
        }
        return $params;
    }

    /**
     * Write the params define_field() cannot reach onto the created row.
     *
     * Function data_field_base::define_field() only reads param1..param5 (mod/data/lib.php),
     * so param6..param10 would be silently dropped for any field type that uses them.
     *
     * @param int $fieldid The created data_fields row id.
     * @param array $spec The field definition.
     */
    protected function write_extra_params(int $fieldid, array $spec): void {
        global $DB;

        $explicit = $this->explicit_params($spec);
        $extras = array_intersect_key($explicit, array_flip(self::EXTRA_PARAMS));
        if (empty($extras)) {
            return;
        }

        $DB->update_record('data_fields', (object) (['id' => $fieldid] + $extras));
    }

    /**
     * Trim and drop blank entries from a list of choice options.
     *
     * @param mixed $options
     * @return string[]
     */
    protected function clean_options($options): array {
        if (!is_array($options)) {
            return [];
        }
        $clean = [];
        foreach ($options as $option) {
            $option = trim((string) $option);
            if ($option !== '') {
                $clean[] = $option;
            }
        }
        return $clean;
    }
}
