namespace local_coursegen\task;

use core\task\adhoc_task;
use core\task\manager;
use local_coursegen\local\service\course_import_service;

/**
 * Adhoc task that imports an AI-generated course into an existing course.
 *
 * Custom data: sessionid, stagingcourseid, targetcourseid. The task runs as
 * the user who requested the import.
 *
 * @package    local_coursegen
 * @copyright  2026 Wilber Narvaez <https://datacurso.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class import_generated_course_task extends adhoc_task {
    /**
     * Queue the import for a planning session.
     *
     * @param int $sessionid Planning session id.
     * @param int $stagingcourseid Course generated by the AI.
     * @param int $targetcourseid Existing course chosen by the user.
     * @param int $userid User requesting the import.
     * @return void
     */
    public static function queue(int $sessionid, int $stagingcourseid, int $targetcourseid, int $userid): void {
        course_import_service::mark_queued($sessionid, $stagingcourseid, $targetcourseid);

        $task = new self();
        $task->set_custom_data([
            'sessionid' => $sessionid,
            'stagingcourseid' => $stagingcourseid,
            'targetcourseid' => $targetcourseid,
        ]);
        $task->set_userid($userid);
        manager::queue_adhoc_task($task);
    }

    /**
     * Localised task name.
     *
     * @return string
     */
    public function get_name(): string {
        return get_string('task_import_generated_course', 'local_coursegen');
    }

    /**
     * Run the import. All bookkeeping (session status, events, rollback) lives in the service.
     *
     * @return void
     */
    public function execute(): void {
        $data = $this->get_custom_data();
        course_import_service::import_into_existing(
            (int)$data->sessionid,
            (int)$data->stagingcourseid,
            (int)$data->targetcourseid,
            (int)$this->get_userid()
        );
    }

    /**
     * Never retry blindly: the original course may already have been renamed.
     *
     * A retry is an explicit user action.
     *
     * @return bool
     */
    public function retry_until_success(): bool {
        return false;
    }
}
