namespace local_coursegen\local;

/**
 * Deletes the drafts of the AI activity editor that lose their owner or their course.
 *
 * @package    local_coursegen
 * @copyright  2026 Wilber Narvaez <https://datacurso.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class draft_observer {
    /**
     * A user was deleted.
     *
     * @param \core\event\user_deleted $event
     */
    public static function user_deleted(\core\event\user_deleted $event): void {
        global $DB;
        $DB->delete_records('local_coursegen_activity_draft', ['userid' => $event->objectid]);
    }

    /**
     * A course was deleted.
     *
     * @param \core\event\course_deleted $event
     */
    public static function course_deleted(\core\event\course_deleted $event): void {
        global $DB;
        $DB->delete_records('local_coursegen_activity_draft', ['courseid' => $event->objectid]);
    }
}
