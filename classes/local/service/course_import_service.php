namespace local_coursegen\local\service;

use core_text;
use local_coursegen\event\generation_failed;
use local_coursegen\event\generation_result_applied;
use local_coursegen\local\models\course_session;

/**
 * Imports an AI-generated (staging) course into an existing course.
 *
 * Strategy (ticket #9539): the original course is renamed with a unique
 * time stamp, a copy of it is created under the original names without any
 * user data, the staging content replaces the copy content, and the staging
 * course is deleted. On any failure the copy is removed, the original names
 * are restored and the staging course is kept so the generated content is
 * never lost.
 *
 * Import bookkeeping is stored as the "import" object inside the session
 * coursedata JSON bag; no schema change is required.
 *
 * @package    local_coursegen
 * @copyright  2026 Wilber Narvaez <https://datacurso.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class course_import_service {
    /** @var string Import state: adhoc task queued. */
    public const STATE_QUEUED = 'queued';

    /** @var string Import state: import in progress. */
    public const STATE_RUNNING = 'running';

    /** @var string Import state: import finished successfully. */
    public const STATE_DONE = 'done';

    /** @var string Import state: import failed and was rolled back. */
    public const STATE_FAILED = 'failed';

    /** @var int Maximum length of course.shortname. */
    private const SHORTNAME_MAXLENGTH = 100;

    /** @var int Maximum length of course.fullname. */
    private const FULLNAME_MAXLENGTH = 254;

    /** @var int Digits of the time stamp suffix. */
    private const STAMP_LENGTH = 10;

    /**
     * Import the staging course into the target course.
     *
     * @param int $sessionid Planning session id.
     * @param int $stagingcourseid Course generated by the AI.
     * @param int $targetcourseid Existing course chosen by the user.
     * @param int $userid Acting user.
     * @return array {success: bool, copycourseid: int, errorclass: string}
     * @throws \required_capability_exception If the user may not run the import; nothing is changed.
     */
    public static function import_into_existing(int $sessionid, int $stagingcourseid, int $targetcourseid, int $userid): array {
        global $DB;

        self::load_backup_libraries();

        $target = $DB->get_record('course', ['id' => $targetcourseid], '*', MUST_EXIST);
        $staging = $DB->get_record('course', ['id' => $stagingcourseid], '*', MUST_EXIST);
        self::require_import_capabilities($target, $staging, $userid);

        $session = new course_session($sessionid);
        self::update_session($session, course_session::STATUS_IMPORTING, null, [
            'targetcourseid' => (int)$target->id,
            'stagingcourseid' => (int)$staging->id,
            'copycourseid' => 0,
            'originalshortname' => $target->shortname,
            'originalfullname' => $target->fullname,
            'renamedshortname' => '',
            'state' => self::STATE_RUNNING,
            'errorclass' => '',
            'timestarted' => time(),
            'timefinished' => 0,
        ]);

        $copyid = 0;
        $renamed = false;
        $tempdirs = [];
        try {
            // Back up the target while it still carries the original names: the
            // restore engine takes the new course names from the backup whenever
            // the name settings are locked for the acting user.
            $backupid = static::backup_course((int)$target->id, \backup::MODE_SAMESITE, $userid, $tempdirs);

            [$names, $copyid] = self::rename_original_and_create_copy($target);
            $renamed = true;
            self::update_session($session, null, null, [
                'copycourseid' => $copyid,
                'renamedshortname' => $names['shortname'],
            ]);

            self::restore_copy_with_original_names($backupid, $target, $copyid, $userid);
            self::replace_copy_content($staging, $copyid, $userid, $tempdirs);
        } catch (\Throwable $e) {
            $copydeleted = self::rollback($target, $copyid, $renamed, $tempdirs);
            self::update_session($session, course_session::STATUS_FAILED, (int)$staging->id, [
                'copycourseid' => $copydeleted ? 0 : $copyid,
                'state' => self::STATE_FAILED,
                'errorclass' => get_class($e),
                'timefinished' => time(),
            ]);
            generation_failed::create([
                'context' => \context_system::instance(),
                'userid' => $userid,
                'other' => ['reason' => get_class($e)],
            ])->trigger();

            return ['success' => false, 'copycourseid' => 0, 'errorclass' => get_class($e)];
        }

        self::remove_temp_dirs($tempdirs);
        // Point the session at the copy before deleting the staging course: the
        // course_deleted observer removes every session bound to a deleted course.
        self::update_session($session, course_session::STATUS_CREATED, $copyid, [
            'state' => self::STATE_DONE,
            'timefinished' => time(),
        ]);
        self::delete_course_bypassing_bin((int)$staging->id);
        generation_result_applied::create([
            'context' => \context_course::instance($copyid),
            'userid' => $userid,
            'other' => ['courseid' => $copyid],
        ])->trigger();

        return ['success' => true, 'copycourseid' => $copyid, 'errorclass' => ''];
    }

    /**
     * Record that the import has been queued for the session.
     *
     * @param int $sessionid Planning session id.
     * @param int $stagingcourseid Course generated by the AI.
     * @param int $targetcourseid Existing course chosen by the user.
     * @return void
     */
    public static function mark_queued(int $sessionid, int $stagingcourseid, int $targetcourseid): void {
        $session = new course_session($sessionid);
        self::update_session($session, null, null, [
            'targetcourseid' => $targetcourseid,
            'stagingcourseid' => $stagingcourseid,
            'state' => self::STATE_QUEUED,
            'errorclass' => '',
        ]);
    }

    /**
     * Compute the names the original course receives while the copy takes its place.
     *
     * Mirrors the delete_user() username pattern: a truncated prefix, a dot
     * and a 10-digit time stamp, incremented while the shortname is taken.
     *
     * @param string $shortname Current shortname.
     * @param string $fullname Current fullname.
     * @param int $stamp Initial time stamp.
     * @return array {shortname: string, fullname: string, stamp: int}
     */
    public static function compute_renamed_names(string $shortname, string $fullname, int $stamp): array {
        global $DB;

        $prefixlength = self::SHORTNAME_MAXLENGTH - 1 - self::STAMP_LENGTH;
        do {
            $newshortname = sprintf('%s.%10d', core_text::substr($shortname, 0, $prefixlength), $stamp);
            $stamp++;
        } while ($DB->record_exists('course', ['shortname' => $newshortname]));
        $usedstamp = $stamp - 1;

        $suffix = ' (' . $usedstamp . ')';
        $newfullname = core_text::substr($fullname, 0, self::FULLNAME_MAXLENGTH - strlen($suffix)) . $suffix;

        return ['shortname' => $newshortname, 'fullname' => $newfullname, 'stamp' => $usedstamp];
    }

    /**
     * Require every capability the import needs, before any write happens.
     *
     * @param \stdClass $target Target course record.
     * @param \stdClass $staging Staging course record.
     * @param int $userid Acting user.
     * @return void
     * @throws \required_capability_exception
     */
    private static function require_import_capabilities(\stdClass $target, \stdClass $staging, int $userid): void {
        $targetcontext = \context_course::instance($target->id);
        require_capability('moodle/backup:backupcourse', $targetcontext, $userid);
        require_capability('moodle/restore:restorecourse', $targetcontext, $userid);
        require_capability('moodle/course:create', \context_coursecat::instance($target->category), $userid);
        require_capability('moodle/backup:backuptargetimport', \context_course::instance($staging->id), $userid);
    }

    /**
     * Rename the original course and create the copy under the original names, in one transaction.
     *
     * There is no unique index on course.shortname, so both steps share a
     * transaction to close the window in which another request could take
     * the freed shortname.
     *
     * @param \stdClass $target Target course record (original names).
     * @return array {0: array names given to the original, 1: int copy course id}
     */
    private static function rename_original_and_create_copy(\stdClass $target): array {
        global $DB;

        $transaction = $DB->start_delegated_transaction();
        $names = self::compute_renamed_names($target->shortname, $target->fullname, time());
        self::set_course_names((int)$target->id, $names['shortname'], $names['fullname']);
        $copyid = (int)\restore_dbops::create_new_course($target->fullname, $target->shortname, $target->category);
        $transaction->allow_commit();

        return [$names, $copyid];
    }

    /**
     * Update the names of a course and invalidate its caches.
     *
     * @param int $courseid Course id.
     * @param string $shortname New shortname.
     * @param string $fullname New fullname.
     * @return void
     */
    private static function set_course_names(int $courseid, string $shortname, string $fullname): void {
        global $DB;

        $DB->update_record('course', (object) [
            'id' => $courseid,
            'shortname' => $shortname,
            'fullname' => $fullname,
            'timemodified' => time(),
        ]);
        rebuild_course_cache($courseid, true);
        \cache_helper::purge_by_event('changesincourse');
    }

    /**
     * Restore the target backup into the copy, keeping the original names.
     *
     * The backup predates the rename, so the engine defaults already hold the
     * original names; they are set explicitly only when the acting user is
     * allowed to change them (otherwise restore_check locks the settings).
     *
     * @param string $backupid Backup of the target course.
     * @param \stdClass $target Target course record (original names).
     * @param int $copyid Copy course id.
     * @param int $userid Acting user.
     * @return void
     */
    private static function restore_copy_with_original_names(string $backupid, \stdClass $target, int $copyid, int $userid): void {
        static::restore_course($backupid, $copyid, $userid, \backup::TARGET_NEW_COURSE, [
            'course_fullname' => $target->fullname,
            'course_shortname' => $target->shortname,
        ]);
    }

    /**
     * Import the staging course onto the copy, deleting the copy content first.
     *
     * @param \stdClass $staging Staging course record.
     * @param int $copyid Copy course id.
     * @param int $userid Acting user.
     * @param string[] $tempdirs Collects backup temp directories to remove.
     * @return void
     */
    private static function replace_copy_content(\stdClass $staging, int $copyid, int $userid, array &$tempdirs): void {
        $backupid = static::backup_course((int)$staging->id, \backup::MODE_IMPORT, $userid, $tempdirs);
        static::restore_course($backupid, $copyid, $userid, \backup::TARGET_EXISTING_DELETING, []);
    }

    /**
     * Run an immediate course backup without user data.
     *
     * @param int $courseid Course to back up.
     * @param int $mode One of the backup::MODE_* constants.
     * @param int $userid Acting user.
     * @param string[] $tempdirs Collects backup temp directories to remove.
     * @return string Backup id.
     */
    protected static function backup_course(int $courseid, int $mode, int $userid, array &$tempdirs): string {
        $bc = new \backup_controller(
            \backup::TYPE_1COURSE,
            $courseid,
            \backup::FORMAT_MOODLE,
            \backup::INTERACTIVE_NO,
            $mode,
            $userid
        );
        $basepath = $bc->get_plan()->get_basepath();
        $tempdirs[] = $basepath;
        // Never carry enrolments, grades or any other user data. The setting is
        // locked by permission when the user lacks moodle/backup:userinfo, and
        // in that case the engine already forced it off.
        $users = $bc->get_plan()->get_setting('users');
        if ($users->get_status() === \base_setting::NOT_LOCKED) {
            $users->set_value(false);
        }
        if ($users->get_value()) {
            $bc->destroy();
            throw new \moodle_exception('error_import_users_setting_locked', 'local_coursegen');
        }
        $backupid = $bc->get_backupid();
        self::execute_silently(function () use ($bc) {
            $bc->execute_plan();
        });
        $results = $bc->get_results();
        $bc->destroy();

        // Outside import mode the engine zips the backup into the course backup
        // area and drops the unpacked directory. Unpack it again for the restore
        // and remove the stored file so nothing is left behind (same as
        // core_course_external::duplicate_course()).
        if (!empty($results['backup_destination'])) {
            $file = $results['backup_destination'];
            if (!file_exists($basepath . '/moodle_backup.xml')) {
                $file->extract_to_pathname(get_file_packer('application/vnd.moodle.backup'), $basepath);
            }
            $file->delete();
        }

        return $backupid;
    }

    /**
     * Run an immediate restore of a backup into a course.
     *
     * @param string $backupid Backup id produced by backup_course().
     * @param int $courseid Destination course id.
     * @param int $userid Acting user.
     * @param int $target One of the backup::TARGET_* constants.
     * @param array $settings Restore settings to override (name => value).
     * @return void
     * @throws \moodle_exception When the restore prechecks report errors.
     */
    protected static function restore_course(string $backupid, int $courseid, int $userid, int $target, array $settings): void {
        $rc = new \restore_controller($backupid, $courseid, \backup::INTERACTIVE_NO, \backup::MODE_SAMESITE, $userid, $target);
        foreach ($settings as $name => $value) {
            $setting = $rc->get_plan()->get_setting($name);
            if ($setting->get_status() === \base_setting::NOT_LOCKED) {
                $setting->set_value($value);
            }
        }
        if (!$rc->execute_precheck()) {
            $results = $rc->get_precheck_results();
            if (!empty($results['errors'])) {
                $rc->destroy();
                throw new \moodle_exception('error_import_precheck_failed', 'local_coursegen');
            }
        }
        self::execute_silently(function () use ($rc) {
            $rc->execute_plan();
        });
        $rc->destroy();
    }

    /**
     * Undo the import: restore the original names, delete the copy, remove temp directories.
     *
     * The staging course is deliberately kept.
     *
     * @param \stdClass $target Target course record (original names).
     * @param int $copyid Copy course id, 0 if it was never created.
     * @param bool $renamed Whether the original was renamed.
     * @param string[] $tempdirs Backup temp directories to remove.
     * @return bool Whether the copy no longer exists.
     */
    private static function rollback(\stdClass $target, int $copyid, bool $renamed, array $tempdirs): bool {
        global $DB;

        $copydeleted = true;
        if ($copyid > 0) {
            try {
                self::delete_course_bypassing_bin($copyid);
            } catch (\Throwable $ignored) {
                // Keep going: restoring the original names matters more. The copy id stays in the session.
                $copydeleted = !$DB->record_exists('course', ['id' => $copyid]);
            }
        }
        if ($renamed) {
            self::set_course_names((int)$target->id, $target->shortname, $target->fullname);
        }
        self::remove_temp_dirs($tempdirs);

        return $copydeleted;
    }

    /**
     * Delete a course without leaving a copy in the recycle bin.
     *
     * Marks the course as a restore artefact, which is what core's restore_ui
     * cleanup does and what tool_recyclebin_pre_course_delete() honours.
     *
     * @param int $courseid Course id.
     * @return void
     */
    private static function delete_course_bypassing_bin(int $courseid): void {
        global $DB;

        $course = $DB->get_record('course', ['id' => $courseid]);
        if (!$course) {
            return;
        }
        $course->deletesource = 'restore';
        delete_course($course, false);
        fix_course_sortorder();
    }

    /**
     * Remove backup temp directories unless the site keeps them for debugging.
     *
     * @param string[] $tempdirs Directories to remove.
     * @return void
     */
    private static function remove_temp_dirs(array $tempdirs): void {
        global $CFG;

        if (!empty($CFG->keeptempdirectoriesonbackup)) {
            return;
        }
        foreach (array_unique($tempdirs) as $dir) {
            if ($dir !== '' && is_dir($dir)) {
                fulldelete($dir);
            }
        }
    }

    /**
     * Persist session status, course id and merged import bookkeeping.
     *
     * Existing keys of the coursedata JSON bag are preserved; only the
     * "import" object is merged.
     *
     * @param course_session $session Session to update.
     * @param int|null $status New status, null to keep.
     * @param int|null $courseid New course id, null to keep.
     * @param array $import Import keys to merge.
     * @return void
     */
    private static function update_session(course_session $session, ?int $status, ?int $courseid, array $import): void {
        $coursedata = json_decode((string)$session->get('coursedata'), true);
        if (!is_array($coursedata)) {
            $coursedata = [];
        }
        $existing = isset($coursedata['import']) && is_array($coursedata['import']) ? $coursedata['import'] : [];
        $coursedata['import'] = array_merge($existing, $import);
        $session->set('coursedata', json_encode($coursedata, JSON_UNESCAPED_UNICODE));
        if ($status !== null) {
            $session->set('status', $status);
        }
        if ($courseid !== null) {
            $session->set('courseid', $courseid);
        }
        $session->update();
    }

    /**
     * Run a backup/restore plan discarding anything third-party steps echo.
     *
     * Some plugins print progress from their restore steps; that output has no
     * place in an adhoc task and must not leak into the cron log.
     *
     * @param callable $callback Plan execution.
     * @return void
     */
    private static function execute_silently(callable $callback): void {
        ob_start();
        try {
            $callback();
        } finally {
            ob_end_clean();
        }
    }

    /**
     * Load the backup and restore libraries.
     *
     * @return void
     */
    private static function load_backup_libraries(): void {
        global $CFG;

        require_once($CFG->dirroot . '/backup/util/includes/backup_includes.php');
        require_once($CFG->dirroot . '/backup/util/includes/restore_includes.php');
    }
}
