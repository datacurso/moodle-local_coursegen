namespace local_coursegen\local\service;

use core_text;
use local_coursegen\event\generation_failed;
use local_coursegen\event\generation_result_applied;
use local_coursegen\local\models\course_session;

/**
 * Imports an AI-generated (staging) course into an existing course.
 *
 * Strategy (ticket #9539): the original course is renamed with a unique
 * time stamp, a copy of it is created under the original names carrying its
 * users (enrolments, roles, groups, grades, completion and activity user
 * data), the staging content is imported into the copy (replacing or adding
 * to it, per the importcontentmode setting; people, roles and groups survive
 * a replace), and the staging course is deleted. The original stays renamed and hidden as a backup. On any failure
 * the copy is removed, the original names and visibility are restored and the
 * staging course is kept so the generated content is never lost.
 *
 * Import bookkeeping is stored as the "import" object inside the session
 * coursedata JSON bag; no schema change is required.
 *
 * @package    local_coursegen
 * @copyright  2026 Wilber Narvaez <https://datacurso.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class course_import_service {
    /** @var string Import state: adhoc task queued. */
    public const STATE_QUEUED = 'queued';

    /** @var string Import state: import in progress. */
    public const STATE_RUNNING = 'running';

    /** @var string Import state: import finished successfully. */
    public const STATE_DONE = 'done';

    /** @var string Import state: import failed and was rolled back. */
    public const STATE_FAILED = 'failed';

    /** @var string Import content mode: delete the copy content before importing the staging course. */
    public const CONTENT_MODE_REPLACE = 'replace';

    /** @var string Import content mode: keep the copy content and add the staging course on top. */
    public const CONTENT_MODE_ADD = 'add';

    /** @var int Maximum length of course.shortname. */
    private const SHORTNAME_MAXLENGTH = 100;

    /** @var int Maximum length of course.fullname. */
    private const FULLNAME_MAXLENGTH = 254;

    /** @var int Digits of the time stamp suffix. */
    private const STAMP_LENGTH = 10;

    /** @var string[] Restore settings the service decides whatever the acting user may configure. */
    private const OWNED_RESTORE_SETTINGS = ['keep_roles_and_enrolments', 'keep_groups_and_groupings'];

    /**
     * Import the staging course into the target course.
     *
     * @param int $sessionid Planning session id.
     * @param int $stagingcourseid Course generated by the AI.
     * @param int $targetcourseid Existing course chosen by the user.
     * @param int $userid Acting user.
     * @return array {success: bool, copycourseid: int, errorclass: string}
     * @throws \required_capability_exception If the user may not run the import; nothing is changed.
     */
    public static function import_into_existing(int $sessionid, int $stagingcourseid, int $targetcourseid, int $userid): array {
        global $DB;

        self::load_backup_libraries();

        $target = $DB->get_record('course', ['id' => $targetcourseid], '*', MUST_EXIST);
        $staging = $DB->get_record('course', ['id' => $stagingcourseid], '*', MUST_EXIST);
        self::require_import_capabilities($target, $staging, $userid);

        $session = new course_session($sessionid);
        self::update_session($session, course_session::STATUS_IMPORTING, null, [
            'targetcourseid' => (int)$target->id,
            'stagingcourseid' => (int)$staging->id,
            'copycourseid' => 0,
            'originalshortname' => $target->shortname,
            'originalfullname' => $target->fullname,
            'originalvisible' => (int)$target->visible,
            'originalvisibleold' => (int)$target->visibleold,
            'renamedshortname' => '',
            'state' => self::STATE_RUNNING,
            'errorclass' => '',
            'timestarted' => time(),
            'timefinished' => 0,
        ]);

        $copyid = 0;
        $renamed = false;
        $tempdirs = [];
        try {
            // Back up the target while it still carries the original names: the
            // restore engine takes the new course names from the backup whenever
            // the name settings are locked for the acting user.
            $backupid = static::backup_course((int)$target->id, \backup::MODE_SAMESITE, $userid, $tempdirs, true);

            [$names, $copyid] = self::rename_original_and_create_copy($target);
            $renamed = true;
            self::update_session($session, null, null, [
                'copycourseid' => $copyid,
                'renamedshortname' => $names['shortname'],
            ]);

            self::restore_copy_with_original_names($backupid, $target, $copyid, $userid);
            self::import_staging_into_copy($staging, $copyid, $userid, $tempdirs);
        } catch (\Throwable $e) {
            $copydeleted = self::rollback($target, $copyid, $renamed, $tempdirs);
            self::update_session($session, course_session::STATUS_FAILED, (int)$staging->id, [
                'copycourseid' => $copydeleted ? 0 : $copyid,
                'state' => self::STATE_FAILED,
                'errorclass' => get_class($e),
                'timefinished' => time(),
            ]);
            generation_failed::create([
                'context' => \context_system::instance(),
                'userid' => $userid,
                'other' => ['reason' => get_class($e)],
            ])->trigger();

            return ['success' => false, 'copycourseid' => 0, 'errorclass' => get_class($e)];
        }

        self::remove_temp_dirs($tempdirs);
        // Point the session at the copy before deleting the staging course: the
        // course_deleted observer removes every session bound to a deleted course.
        self::update_session($session, course_session::STATUS_CREATED, $copyid, [
            'state' => self::STATE_DONE,
            'timefinished' => time(),
        ]);
        self::delete_course_bypassing_bin((int)$staging->id);
        generation_result_applied::create([
            'context' => \context_course::instance($copyid),
            'userid' => $userid,
            'other' => ['courseid' => $copyid],
        ])->trigger();

        return ['success' => true, 'copycourseid' => $copyid, 'errorclass' => ''];
    }

    /**
     * Record that the import has been queued for the session.
     *
     * @param int $sessionid Planning session id.
     * @param int $stagingcourseid Course generated by the AI.
     * @param int $targetcourseid Existing course chosen by the user.
     * @return void
     */
    public static function mark_queued(int $sessionid, int $stagingcourseid, int $targetcourseid): void {
        $session = new course_session($sessionid);
        self::update_session($session, null, null, [
            'targetcourseid' => $targetcourseid,
            'stagingcourseid' => $stagingcourseid,
            'state' => self::STATE_QUEUED,
            'errorclass' => '',
        ]);
    }

    /**
     * Compute the names the original course receives while the copy takes its place.
     *
     * Mirrors the delete_user() username pattern: a truncated prefix, a dot
     * and a 10-digit time stamp, incremented while the shortname is taken.
     *
     * @param string $shortname Current shortname.
     * @param string $fullname Current fullname.
     * @param int $stamp Initial time stamp.
     * @return array {shortname: string, fullname: string, stamp: int}
     */
    public static function compute_renamed_names(string $shortname, string $fullname, int $stamp): array {
        global $DB;

        $prefixlength = self::SHORTNAME_MAXLENGTH - 1 - self::STAMP_LENGTH;
        do {
            $newshortname = sprintf('%s.%10d', core_text::substr($shortname, 0, $prefixlength), $stamp);
            $stamp++;
        } while ($DB->record_exists('course', ['shortname' => $newshortname]));
        $usedstamp = $stamp - 1;

        $suffix = ' (' . $usedstamp . ')';
        $newfullname = core_text::substr($fullname, 0, self::FULLNAME_MAXLENGTH - strlen($suffix)) . $suffix;

        return ['shortname' => $newshortname, 'fullname' => $newfullname, 'stamp' => $usedstamp];
    }

    /**
     * Require every capability the import needs, before any write happens.
     *
     * The target set is import_permissions; moodle/backup:backuptargetimport
     * is checked here on the staging course, which only exists at this point.
     *
     * @param \stdClass $target Target course record.
     * @param \stdClass $staging Staging course record.
     * @param int $userid Acting user.
     * @return void
     * @throws \required_capability_exception
     */
    private static function require_import_capabilities(\stdClass $target, \stdClass $staging, int $userid): void {
        import_permissions::require_for_target($target, $userid);
        require_capability('moodle/backup:backuptargetimport', \context_course::instance($staging->id), $userid);
    }

    /**
     * Rename and hide the original course and create the copy under the original names, in one transaction.
     *
     * There is no unique index on course.shortname, so both steps share a
     * transaction to close the window in which another request could take
     * the freed shortname. The original is hidden in the same step so that
     * rollback() covers it: it stays hidden and renamed when the import succeeds.
     *
     * @param \stdClass $target Target course record (original names and visibility).
     * @return array {0: array names given to the original, 1: int copy course id}
     */
    private static function rename_original_and_create_copy(\stdClass $target): array {
        global $DB;

        $transaction = $DB->start_delegated_transaction();
        $names = self::compute_renamed_names($target->shortname, $target->fullname, time());
        self::set_course_names((int)$target->id, $names['shortname'], $names['fullname']);
        self::set_course_visibility((int)$target->id, 0, 0);
        $copyid = (int)\restore_dbops::create_new_course($target->fullname, $target->shortname, $target->category);
        $transaction->allow_commit();

        return [$names, $copyid];
    }

    /**
     * Update the names of a course and invalidate its caches.
     *
     * @param int $courseid Course id.
     * @param string $shortname New shortname.
     * @param string $fullname New fullname.
     * @return void
     */
    private static function set_course_names(int $courseid, string $shortname, string $fullname): void {
        global $DB;

        $DB->update_record('course', (object) [
            'id' => $courseid,
            'shortname' => $shortname,
            'fullname' => $fullname,
            'timemodified' => time(),
        ]);
        rebuild_course_cache($courseid, true);
        \cache_helper::purge_by_event('changesincourse');
    }

    /**
     * Set the visibility flags of a course the way course_change_visibility() does.
     *
     * Mirrors the visibility path of update_course(): both flags are written,
     * the course caches are rebuilt and purged, and a course_updated event is
     * triggered. The flags are written directly so the rollback can restore
     * the exact previous values; course_change_visibility() always sets
     * visibleold equal to visible, which would lose a course hidden by its
     * category. No capability check happens here: callers hold
     * moodle/course:visibility (see require_import_capabilities()).
     *
     * @param int $courseid Course id.
     * @param int $visible New course.visible value (0 or 1).
     * @param int $visibleold New course.visibleold value (0 or 1).
     * @return void
     */
    private static function set_course_visibility(int $courseid, int $visible, int $visibleold): void {
        global $DB;

        $DB->update_record('course', (object) [
            'id' => $courseid,
            'visible' => $visible,
            'visibleold' => $visibleold,
            'timemodified' => time(),
        ]);
        rebuild_course_cache($courseid, true);
        \cache_helper::purge_by_event('changesincourse');
        \cache_helper::purge_by_event('changesincoursecat');

        $course = $DB->get_record('course', ['id' => $courseid], 'id, shortname, fullname', MUST_EXIST);
        \core\event\course_updated::create([
            'objectid' => $courseid,
            'context' => \context_course::instance($courseid),
            'other' => [
                'shortname' => $course->shortname,
                'fullname' => $course->fullname,
                'updatedfields' => ['visible' => $visible, 'visibleold' => $visibleold],
            ],
        ])->trigger();
    }

    /**
     * Restore the target backup into the copy, keeping the original names and all the user data.
     *
     * The backup predates the rename, so the engine defaults already hold the
     * original names; they are set explicitly only when the acting user is
     * allowed to change them (otherwise restore_check locks the settings).
     * The user data settings mirror a full restore with users: enrolment
     * instances with their user enrolments, role assignments, completion and
     * grade histories; groups, memberships and activity user data follow the
     * "users" setting.
     *
     * @param string $backupid Backup of the target course.
     * @param \stdClass $target Target course record (original names).
     * @param int $copyid Copy course id.
     * @param int $userid Acting user.
     * @return void
     */
    private static function restore_copy_with_original_names(string $backupid, \stdClass $target, int $copyid, int $userid): void {
        static::restore_course($backupid, $copyid, $userid, \backup::TARGET_NEW_COURSE, [
            'course_fullname' => $target->fullname,
            'course_shortname' => $target->shortname,
            'users' => true,
            'enrolments' => \backup::ENROL_WITHUSERS,
            'role_assignments' => true,
            'userscompletion' => true,
            'grade_histories' => true,
        ]);
    }

    /**
     * Import the staging course onto the copy, replacing or adding to its content.
     *
     * The admin setting local_coursegen/importcontentmode decides the restore
     * target: "add" keeps the copy sections and activities untouched and
     * appends the staging sections after them (see backup_staging_appended());
     * any other value deletes the copy content first, keeping its enrolments,
     * role assignments, groups and groupings.
     *
     * @param \stdClass $staging Staging course record.
     * @param int $copyid Copy course id.
     * @param int $userid Acting user.
     * @param string[] $tempdirs Collects backup temp directories to remove.
     * @return void
     */
    private static function import_staging_into_copy(\stdClass $staging, int $copyid, int $userid, array &$tempdirs): void {
        $target = self::get_import_target();
        if ($target === \backup::TARGET_EXISTING_ADDING) {
            $backupid = self::backup_staging_appended((int)$staging->id, $copyid, $userid, $tempdirs);
            static::restore_course($backupid, $copyid, $userid, $target, []);
            self::extend_numsections($copyid);
            return;
        }
        $backupid = static::backup_course((int)$staging->id, \backup::MODE_IMPORT, $userid, $tempdirs, false);
        static::restore_course($backupid, $copyid, $userid, $target, [
            'keep_roles_and_enrolments' => true,
            'keep_groups_and_groupings' => true,
        ]);
    }

    /**
     * Back up the staging course with its sections numbered after the copy's last section.
     *
     * The restore engine matches sections by number: an existing section keeps
     * its name and summary and receives the incoming activities. To append
     * instead of merging, the staging sections are shifted past the copy's
     * highest number T while the backup is taken. The AI plan numbers its
     * sections from zero, so the staging's section 0 is usually a real section
     * (named, with a summary or with modules): it is then materialised as a new
     * section T+1 and the rest are shifted by T+1 so they follow it. Section 0
     * itself is left blank so merging it into the copy's section 0 changes
     * nothing there. The shift is undone right after the backup, so a later
     * failure never leaves the staging course with gaps in its numbering.
     *
     * @param int $stagingid Staging course id.
     * @param int $copyid Copy course id (already holding the target sections).
     * @param int $userid Acting user.
     * @param string[] $tempdirs Collects backup temp directories to remove.
     * @return string Backup id.
     */
    private static function backup_staging_appended(int $stagingid, int $copyid, int $userid, array &$tempdirs): string {
        global $DB;

        $snapshot = self::snapshot_section_layout($stagingid);
        try {
            $offset = (int)$DB->get_field_sql('SELECT MAX(section) FROM {course_sections} WHERE course = ?', [$copyid]);
            $zero = $DB->get_record(
                'course_sections',
                ['course' => $stagingid, 'section' => 0],
                'id, name, summary, summaryformat, sequence',
                MUST_EXIST
            );
            $zeromodules = self::section_zero_modules($stagingid, $zero);
            $materialise = $zeromodules || (string)$zero->name !== '' || (string)$zero->summary !== '';
            self::shift_section_numbers($stagingid, $materialise ? $offset + 1 : $offset);
            if ($materialise) {
                self::materialise_section_zero($stagingid, $zero, $zeromodules, $offset + 1);
            }
            rebuild_course_cache($stagingid, true);
            return static::backup_course($stagingid, \backup::MODE_IMPORT, $userid, $tempdirs, false);
        } finally {
            self::restore_section_layout($stagingid, $snapshot);
            rebuild_course_cache($stagingid, true);
        }
    }

    /**
     * Shift every section but section 0 by the given offset.
     *
     * Updated in descending order because of the unique (course, section) index.
     * Delegated sections (mod_subsection) are shifted with the rest: only their
     * number orders them, nothing else stores it.
     *
     * @param int $courseid Course id.
     * @param int $offset Amount to add to each section number.
     * @return void
     */
    private static function shift_section_numbers(int $courseid, int $offset): void {
        global $DB;

        if ($offset <= 0) {
            return;
        }
        $sections = $DB->get_records_select(
            'course_sections',
            'course = ? AND section > 0',
            [$courseid],
            'section DESC',
            'id, section'
        );
        foreach ($sections as $section) {
            $DB->set_field('course_sections', 'section', $section->section + $offset, ['id' => $section->id]);
        }
    }

    /**
     * Ids of the modules placed in section 0, in sequence order (modules missing from the sequence go last).
     *
     * @param int $courseid Course id.
     * @param \stdClass $zero Section 0 record (id, sequence).
     * @return int[]
     */
    private static function section_zero_modules(int $courseid, \stdClass $zero): array {
        global $DB;

        $cmids = array_map(
            'intval',
            $DB->get_fieldset_select('course_modules', 'id', 'course = ? AND section = ?', [$courseid, $zero->id])
        );
        $sequence = array_map('intval', array_filter(explode(',', (string)$zero->sequence)));
        return array_merge(array_values(array_intersect($sequence, $cmids)), array_values(array_diff($cmids, $sequence)));
    }

    /**
     * Turn section 0 into a regular section with the given number and blank section 0.
     *
     * A new section row is created carrying the name, summary and modules of
     * section 0; the modules keep their order. Section 0 is left with an empty
     * sequence, name and summary so merging it into the copy's section 0
     * changes nothing there (the restore only fills an empty name or summary).
     * The row is transient: restore_section_layout() removes it after the backup.
     *
     * @param int $courseid Course id.
     * @param \stdClass $zero Section 0 record (id, name, summary, summaryformat).
     * @param int[] $cmids Modules of section 0 in sequence order.
     * @param int $number Section number the new section takes; must be free.
     * @return void
     */
    private static function materialise_section_zero(int $courseid, \stdClass $zero, array $cmids, int $number): void {
        global $DB;

        $section = (object) [
            'course' => $courseid,
            'section' => $number,
            'name' => $zero->name,
            'summary' => (string)$zero->summary,
            'summaryformat' => (int)$zero->summaryformat,
            'sequence' => implode(',', $cmids),
            'visible' => 1,
            'timemodified' => time(),
        ];
        $section->id = $DB->insert_record('course_sections', $section);
        if ($cmids) {
            [$insql, $params] = $DB->get_in_or_equal($cmids);
            $DB->set_field_select('course_modules', 'section', $section->id, "id $insql", $params);
        }
        $DB->update_record('course_sections', (object) ['id' => $zero->id, 'sequence' => '', 'name' => null, 'summary' => '']);
    }

    /**
     * Capture the section numbering and module placement of a course.
     *
     * @param int $courseid Course id.
     * @return array {sections: \stdClass[] keyed by id, modules: int[] section id keyed by cm id}
     */
    private static function snapshot_section_layout(int $courseid): array {
        global $DB;

        return [
            'sections' => $DB->get_records(
                'course_sections',
                ['course' => $courseid],
                'section ASC',
                'id, section, name, summary, sequence'
            ),
            'modules' => $DB->get_records_menu('course_modules', ['course' => $courseid], '', 'id, section'),
        ];
    }

    /**
     * Put back the section layout captured by snapshot_section_layout().
     *
     * Sections that did not exist in the snapshot are removed. Numbers are
     * restored in ascending snapshot order: a shifted section always moves to
     * a number lower than its current one that no other row can hold yet, so
     * the unique (course, section) index is never hit.
     *
     * @param int $courseid Course id.
     * @param array $snapshot Layout captured before the renumbering.
     * @return void
     */
    private static function restore_section_layout(int $courseid, array $snapshot): void {
        global $DB;

        $current = $DB->get_fieldset_select('course_sections', 'id', 'course = ?', [$courseid]);
        foreach (array_diff($current, array_keys($snapshot['sections'])) as $id) {
            $DB->delete_records('course_sections', ['id' => $id]);
        }
        foreach ($snapshot['modules'] as $cmid => $sectionid) {
            $DB->set_field('course_modules', 'section', $sectionid, ['id' => $cmid]);
        }
        foreach ($snapshot['sections'] as $section) {
            $DB->update_record('course_sections', $section);
        }
    }

    /**
     * Raise the "numsections" format option of a course to its last regular section, when the format has one.
     *
     * The course.xml step is skipped when restoring onto an existing course, so
     * nothing else updates the option after sections are appended. Core formats
     * no longer use it; third-party formats may.
     *
     * @param int $courseid Course id.
     * @return void
     */
    private static function extend_numsections(int $courseid): void {
        global $DB;

        $format = course_get_format($courseid);
        $options = $format->get_format_options();
        if (!isset($options['numsections'])) {
            return;
        }
        $last = (int)$DB->get_field_sql(
            'SELECT MAX(section) FROM {course_sections} WHERE course = ? AND component IS NULL',
            [$courseid]
        );
        if ($last > (int)$options['numsections']) {
            $format->update_course_format_options(['numsections' => $last]);
            rebuild_course_cache($courseid, true);
        }
    }

    /**
     * Resolve the restore target from the import content mode setting.
     *
     * @return int backup::TARGET_EXISTING_ADDING for "add", backup::TARGET_EXISTING_DELETING otherwise.
     */
    private static function get_import_target(): int {
        $mode = (string)get_config('local_coursegen', 'importcontentmode');
        if ($mode === self::CONTENT_MODE_ADD) {
            return \backup::TARGET_EXISTING_ADDING;
        }
        return \backup::TARGET_EXISTING_DELETING;
    }

    /**
     * Run an immediate course backup, with or without user data.
     *
     * @param int $courseid Course to back up.
     * @param int $mode One of the backup::MODE_* constants.
     * @param int $userid Acting user.
     * @param string[] $tempdirs Collects backup temp directories to remove.
     * @param bool $withusers Whether to include enrolments, grades and every other user data.
     * @return string Backup id.
     * @throws \moodle_exception When user data is required but the "users" setting is locked off.
     */
    protected static function backup_course(int $courseid, int $mode, int $userid, array &$tempdirs, bool $withusers): string {
        $bc = new \backup_controller(
            \backup::TYPE_1COURSE,
            $courseid,
            \backup::FORMAT_MOODLE,
            \backup::INTERACTIVE_NO,
            $mode,
            $userid
        );
        $basepath = $bc->get_plan()->get_basepath();
        $tempdirs[] = $basepath;
        // The engine locks the setting (forced off) when the user lacks
        // moodle/backup:userinfo, and locks every setting at its default when
        // the user lacks moodle/backup:configure; import mode always forces it off.
        $users = $bc->get_plan()->get_setting('users');
        if ($users->get_status() === \base_setting::NOT_LOCKED) {
            $users->set_value($withusers);
        }
        if ($withusers && !$users->get_value()) {
            $bc->destroy();
            throw new \moodle_exception('error_import_users_required', 'local_coursegen');
        }
        $backupid = $bc->get_backupid();
        self::execute_silently(function () use ($bc) {
            $bc->execute_plan();
        });
        $results = $bc->get_results();
        $bc->destroy();

        // Outside import mode the engine zips the backup into the course backup
        // area and drops the unpacked directory. Unpack it again for the restore
        // and remove the stored file so nothing is left behind (same as
        // core_course_external::duplicate_course()).
        if (!empty($results['backup_destination'])) {
            $file = $results['backup_destination'];
            if (!file_exists($basepath . '/moodle_backup.xml')) {
                $file->extract_to_pathname(get_file_packer('application/vnd.moodle.backup'), $basepath);
            }
            $file->delete();
        }

        return $backupid;
    }

    /**
     * Run an immediate restore of a backup into a course.
     *
     * @param string $backupid Backup id produced by backup_course().
     * @param int $courseid Destination course id.
     * @param int $userid Acting user.
     * @param int $target One of the backup::TARGET_* constants.
     * @param array $settings Restore settings to override (name => value); unknown names are ignored,
     *                        locked settings keep their value except OWNED_RESTORE_SETTINGS.
     * @return void
     * @throws \moodle_exception When the restore prechecks report errors, or when user data was
     *                           requested but the "users" setting is locked off.
     */
    protected static function restore_course(string $backupid, int $courseid, int $userid, int $target, array $settings): void {
        $rc = new \restore_controller($backupid, $courseid, \backup::INTERACTIVE_NO, \backup::MODE_SAMESITE, $userid, $target);
        $plan = $rc->get_plan();
        foreach ($settings as $name => $value) {
            if (!$plan->setting_exists($name)) {
                continue;
            }
            $setting = $plan->get_setting($name);
            if (in_array($name, self::OWNED_RESTORE_SETTINGS, true)) {
                self::set_owned_setting_value($setting, $value);
            } else if ($setting->get_status() === \base_setting::NOT_LOCKED) {
                $setting->set_value($value);
            }
        }
        if (!empty($settings['users']) && !$plan->get_setting('users')->get_value()) {
            $rc->destroy();
            throw new \moodle_exception('error_import_users_required', 'local_coursegen');
        }
        if (!$rc->execute_precheck()) {
            $results = $rc->get_precheck_results();
            if (!empty($results['errors'])) {
                $rc->destroy();
                throw new \moodle_exception('error_import_precheck_failed', 'local_coursegen');
            }
        }
        self::execute_silently(function () use ($rc) {
            $rc->execute_plan();
        });
        $rc->destroy();
    }

    /**
     * Set a restore setting the service owns, lifting a permission lock for the write.
     *
     * The engine locks every setting by permission when the acting user lacks
     * moodle/restore:configure. The keep_roles_and_enrolments and
     * keep_groups_and_groupings settings of a deleting restore have no
     * capability of their own and the user never configures this restore, so
     * the lock is lifted for the write and put back, the way core's course
     * copy task does with the "users" setting. A lock set by site
     * configuration is respected.
     *
     * @param \base_setting $setting Setting to write.
     * @param mixed $value Value to set.
     * @return void
     */
    private static function set_owned_setting_value(\base_setting $setting, $value): void {
        $status = $setting->get_status();
        if ($status === \base_setting::LOCKED_BY_CONFIG) {
            return;
        }
        if ($status !== \base_setting::NOT_LOCKED) {
            $setting->set_status(\base_setting::NOT_LOCKED);
        }
        $setting->set_value($value);
        if ($status !== \base_setting::NOT_LOCKED) {
            $setting->set_status($status);
        }
    }

    /**
     * Undo the import: restore the original names and visibility, delete the copy, remove temp directories.
     *
     * The staging course is deliberately kept.
     *
     * @param \stdClass $target Target course record (original names and visibility).
     * @param int $copyid Copy course id, 0 if it was never created.
     * @param bool $renamed Whether the original was renamed.
     * @param string[] $tempdirs Backup temp directories to remove.
     * @return bool Whether the copy no longer exists.
     */
    private static function rollback(\stdClass $target, int $copyid, bool $renamed, array $tempdirs): bool {
        global $DB;

        $copydeleted = true;
        if ($copyid > 0) {
            try {
                self::delete_course_bypassing_bin($copyid);
            } catch (\Throwable $ignored) {
                // Keep going: restoring the original names matters more. The copy id stays in the session.
                $copydeleted = !$DB->record_exists('course', ['id' => $copyid]);
            }
        }
        if ($renamed) {
            self::set_course_names((int)$target->id, $target->shortname, $target->fullname);
            self::set_course_visibility((int)$target->id, (int)$target->visible, (int)$target->visibleold);
        }
        self::remove_temp_dirs($tempdirs);

        return $copydeleted;
    }

    /**
     * Delete a course without leaving a copy in the recycle bin.
     *
     * Marks the course as a restore artefact, which is what core's restore_ui
     * cleanup does and what tool_recyclebin_pre_course_delete() honours.
     *
     * @param int $courseid Course id.
     * @return void
     */
    private static function delete_course_bypassing_bin(int $courseid): void {
        global $DB;

        $course = $DB->get_record('course', ['id' => $courseid]);
        if (!$course) {
            return;
        }
        $course->deletesource = 'restore';
        delete_course($course, false);
        fix_course_sortorder();
    }

    /**
     * Remove backup temp directories unless the site keeps them for debugging.
     *
     * @param string[] $tempdirs Directories to remove.
     * @return void
     */
    private static function remove_temp_dirs(array $tempdirs): void {
        global $CFG;

        if (!empty($CFG->keeptempdirectoriesonbackup)) {
            return;
        }
        foreach (array_unique($tempdirs) as $dir) {
            if ($dir !== '' && is_dir($dir)) {
                fulldelete($dir);
            }
        }
    }

    /**
     * Persist session status, course id and merged import bookkeeping.
     *
     * Existing keys of the coursedata JSON bag are preserved; only the
     * "import" object is merged.
     *
     * @param course_session $session Session to update.
     * @param int|null $status New status, null to keep.
     * @param int|null $courseid New course id, null to keep.
     * @param array $import Import keys to merge.
     * @return void
     */
    private static function update_session(course_session $session, ?int $status, ?int $courseid, array $import): void {
        $coursedata = json_decode((string)$session->get('coursedata'), true);
        if (!is_array($coursedata)) {
            $coursedata = [];
        }
        $existing = isset($coursedata['import']) && is_array($coursedata['import']) ? $coursedata['import'] : [];
        $coursedata['import'] = array_merge($existing, $import);
        $session->set('coursedata', json_encode($coursedata, JSON_UNESCAPED_UNICODE));
        if ($status !== null) {
            $session->set('status', $status);
        }
        if ($courseid !== null) {
            $session->set('courseid', $courseid);
        }
        $session->update();
    }

    /**
     * Run a backup/restore plan discarding anything third-party steps echo.
     *
     * Some plugins print progress from their restore steps; that output has no
     * place in an adhoc task and must not leak into the cron log.
     *
     * @param callable $callback Plan execution.
     * @return void
     */
    private static function execute_silently(callable $callback): void {
        ob_start();
        try {
            $callback();
        } finally {
            ob_end_clean();
        }
    }

    /**
     * Load the backup and restore libraries.
     *
     * @return void
     */
    private static function load_backup_libraries(): void {
        global $CFG;

        require_once($CFG->dirroot . '/backup/util/includes/backup_includes.php');
        require_once($CFG->dirroot . '/backup/util/includes/restore_includes.php');
    }
